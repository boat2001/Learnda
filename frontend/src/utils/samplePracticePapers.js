const dedupeById = (items = []) => {
  const seen = new Set();
  return items.filter((item) => {
    const key = safeText(item?.id);
    if (!key || seen.has(key)) return false;
    seen.add(key);
    return true;
  });
};

const matchesCourseAlias = (courseTitle = '', item = {}) => {
  const normalizedCourse = normalize(courseTitle);
  if (!normalizedCourse) return false;

  const aliases = [
    item?.course,
    ...(Array.isArray(item?.metadata?.course_aliases) ? item.metadata.course_aliases : []),
  ]
    .map(normalize)
    .filter(Boolean);

  return aliases.some((alias) => normalizedCourse === alias || normalizedCourse.includes(alias) || alias.includes(normalizedCourse));
};

export const findSamplePracticeById = (practiceId) =>
  SAMPLE_PRACTICE_PAPERS.find((item) => String(item.id) === String(practiceId)) || null;

export const getSamplePracticeItemsForCourse = (courseTitle = '', type = '') =>
  dedupeById(
    SAMPLE_PRACTICE_PAPERS.filter((item) => {
      if (type && normalize(item.type) !== normalize(type)) return false;
      return matchesCourseAlias(courseTitle, item);
    })
  );

export const searchSamplePracticeItems = (query = '') => {
  const normalizedQuery = normalize(query);
  if (!normalizedQuery) return [];

  return dedupeById(
    SAMPLE_PRACTICE_PAPERS.filter((item) => {
      const haystack = [
        item?.title,
        item?.description,
        item?.course,
        item?.metadata?.course_code,
        item?.metadata?.source_title,
        item?.metadata?.source_label,
        ...(item?.tags || []),
      ]
        .map(normalize)
        .join(' ');

      return haystack.includes(normalizedQuery);
    })
  );
};
